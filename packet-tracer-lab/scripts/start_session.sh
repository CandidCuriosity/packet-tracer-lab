#!/usr/bin/env bash
# Restore a Notebook desktop/PT, or only wait with --no-recover.
# Exit: 0 PT process/window stable; 1 recovery/precondition/timeout; 2 invalid arguments.
set -u
DESKTOP_DIR=${DESKTOP_DIR:-/mnt/workspace/desktop}
RECOVER=${RECOVER:-/mnt/workspace/recover-packettracer.sh}
RUN="$DESKTOP_DIR/bin/desktop-run"
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PYTHON=${PT_PYTHON:-python3}
CHECK="$SCRIPT_DIR/pt_runtime.py"
DO_RECOVER=1
TIMEOUT=180
while [ "$#" -gt 0 ]; do
  case "$1" in
    --no-recover) DO_RECOVER=0 ;;
    --timeout)
      [ "$#" -ge 2 ] || { echo "--timeout requires seconds" >&2; exit 2; }
      shift
      TIMEOUT=$1
      case "$TIMEOUT" in ''|*[!0-9]*|0) echo "--timeout must be a positive integer" >&2; exit 2 ;; esac
      ;;
    -h|--help) echo "Usage: bash start_session.sh [--no-recover] [--timeout SECONDS]"; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done
# Match WM_CLASS + PID, not the login browser's identical title.
if [ -x "$RUN" ]; then
  if "$PYTHON" "$CHECK" --once >/dev/null; then
    echo "PT process/window present; verifying identity stability before reuse."
    "$PYTHON" "$CHECK" --timeout "$TIMEOUT" --stable-seconds 1 || exit 1
    echo "PT process/window stable; recovery skipped. Confirm a real PT readback separately."
    exit 0
  fi
fi
if [ "$DO_RECOVER" -eq 1 ]; then
  [ -r "$RECOVER" ] || { echo "Missing recovery script: $RECOVER" >&2; exit 1; }
  # desktop-run may be GENERATED by this script; check it AFTER recovery.
  bash "$RECOVER" || { echo "Recovery failed; preserve existing PT and inspect its logs." >&2; exit 1; }
fi
[ -x "$RUN" ] || { echo "Missing desktop-run after recovery: $RUN" >&2; exit 1; }
if "$PYTHON" "$CHECK" --timeout "$TIMEOUT" --stable-seconds 1; then
  echo "PT process/window stable. Next: confirm bridge AND a real PT readback in Codex."
  exit 0
fi
echo "PT window timeout. Check start-desktop.sh status/doctor and probe_env.sh --phase ready." >&2
exit 1
